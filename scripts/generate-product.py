"""Generate or check the product header, without changing compatibility fields."""
import sys
from pathlib import Path
from product import VERSION

path = Path(__file__).resolve().parents[1] / 'firmware/Common/prox_product.h'
major, minor, patch = map(int, VERSION.split('.'))
content = f'''/* Generated by scripts/generate-product.py; not a Sony/HEN version. */
#ifndef PROX_PRODUCT_H
#define PROX_PRODUCT_H
#define PROX_PRODUCT_VERSION "{VERSION}"
#define PROX_PRODUCT_MAJOR {major}
#define PROX_PRODUCT_MINOR {minor}
#define PROX_PRODUCT_PATCH {patch}
#endif
'''
if '--check' in sys.argv:
    if path.read_text() != content:
        raise SystemExit('Product header differs from scripts/product.py')
else:
    path.write_text(content, encoding='ascii', newline='\n')
make_path = path.with_suffix('.mk')
make_content = '# Generated by scripts/generate-product.py; product version, not Sony firmware.\nPROX_PRODUCT_VERSION = '+VERSION+'\n'
if '--check' in sys.argv:
    if make_path.read_text() != make_content:
        raise SystemExit('Product makefile differs from scripts/product.py')
else:
    make_path.write_text(make_content, encoding='ascii', newline='\n')
